// ErrConfigFileExists is returned when attempting to initialize a config file that already exists without force.
var ErrConfigFileExists = errors.New("configuration file already exists")

// Config encapsulates runtime parameters for the Matrix rain simulation.
type Config struct {
	FPS             int
	Density         int     // 1 - 100
	SpeedScale      float64 // Multiplier for drop speeds (e.g., 0.5x - 3.0x)
	ThemeName       string
	CharSetName     string
	BoldHead        bool
	FilePath        string  // Optional path to text file
	FileContent     []byte  // Optional raw text content
	Center          bool    // Center text on screen
	Loop            bool    // Keep ambient rain falling after text settles
	TabWidth        int     // Width of tab expansion (default 4)
	SyntaxHighlight bool    // Enable syntax highlighting (default true)
	SyntaxTheme     string  // Syntax theme (e.g. monokai, dracula, nord, etc.)
	ConfigFile      string  // Path to loaded configuration file, if any
}

// DefaultConfig returns production-ready default settings.
func DefaultConfig() Config {
	return Config{
		FPS:             30,
		Density:         50,
		SpeedScale:      1.0,
		ThemeName:       "green",
		CharSetName:     string(CharSetMatrix),
		BoldHead:        true,
		TabWidth:        4,
		SyntaxHighlight: true,
		SyntaxTheme:     "monokai",
	}
}

// DefaultConfigPath returns the default path to the user configuration file (~/.mcatrc).
func DefaultConfigPath() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", fmt.Errorf("failed to locate user home directory: %w", err)
	}
	return filepath.Join(home, ".mcatrc"), nil
}

